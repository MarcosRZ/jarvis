import { promises as fs } from "node:fs";
import path from "node:path";
import {
  clientSettingKeys,
  isKnownSetting,
  serverSettingKeys,
  settingField,
  validateSettingValue,
} from "@/lib/settings-schema";

const settingsFile = "/data/settings.json";
const maxValueLength = 4000;

type SettingsPayload = {
  values?: unknown;
};

type StoredSettings = {
  version: 1;
  updatedAt: string;
  values: Record<string, string>;
};

export class InvalidSettingsError extends Error {}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export async function readSettings(): Promise<Record<string, string>> {
  let raw: string;
  try {
    raw = await fs.readFile(settingsFile, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      return {};
    }
    throw error;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw) as unknown;
  } catch {
    throw new InvalidSettingsError("Cannot parse the saved settings.");
  }
  if (!isRecord(parsed) || !isRecord(parsed.values)) {
    return {};
  }
  const values: Record<string, string> = {};
  for (const [key, value] of Object.entries(parsed.values)) {
    if (isKnownSetting(key) && typeof value === "string" && value !== "") {
      values[key] = value;
    }
  }
  return values;
}

export function parseSettingsBody(body: unknown): Record<string, string> {
  if (!isRecord(body) || !isRecord((body as SettingsPayload).values)) {
    throw new InvalidSettingsError("values must be an object.");
  }
  const input = (body as SettingsPayload).values as Record<string, unknown>;
  const values: Record<string, string> = {};
  for (const [key, raw] of Object.entries(input)) {
    if (typeof raw !== "string") {
      throw new InvalidSettingsError(`${key} must be a string.`);
    }
    if (raw === "") {
      continue;
    }
    if (raw.length > maxValueLength) {
      throw new InvalidSettingsError(`${key} is too long.`);
    }
    if (!isKnownSetting(key)) {
      throw new InvalidSettingsError(`${key} is not a known setting.`);
    }
    const field = settingField(key);
    if (!field) {
      throw new InvalidSettingsError(`${key} is not a known setting.`);
    }
    const problem = validateSettingValue(field, raw);
    if (problem) {
      throw new InvalidSettingsError(problem);
    }
    values[key] = raw;
  }
  return values;
}

export async function saveSettings(
  values: Record<string, string>,
): Promise<Record<string, string>> {
  const stored: StoredSettings = {
    version: 1,
    updatedAt: new Date().toISOString(),
    values,
  };
  const directory = path.dirname(settingsFile);
  const temporary = `${settingsFile}.${process.pid}.tmp`;
  try {
    await fs.mkdir(directory, { recursive: true, mode: 0o700 });
    await fs.writeFile(temporary, JSON.stringify(stored, null, 2), {
      mode: 0o600,
    });
    await fs.rename(temporary, settingsFile);
  } catch (error) {
    await fs.rm(temporary, { force: true }).catch(() => undefined);
    throw error;
  }
  return values;
}

function filterValues(
  values: Record<string, string>,
  keys: string[],
): Record<string, string> {
  const result: Record<string, string> = {};
  for (const key of keys) {
    const value = values[key];
    if (typeof value === "string" && value !== "") {
      result[key] = value;
    }
  }
  return result;
}

export function clientValues(
  values: Record<string, string>,
): Record<string, string> {
  return filterValues(values, clientSettingKeys());
}

export function composeScript(values: Record<string, string>): string {
  const lines = ["# Generated by M4nhattan Settings. Do not edit."];
  const exported = filterValues(values, serverSettingKeys());
  for (const key of serverSettingKeys()) {
    const value = exported[key];
    if (value === undefined) {
      continue;
    }
    const escaped = value.replace(/'/g, "'\\''");
    lines.push(`export ${key}='${escaped}'`);
  }
  return `${lines.join("\n")}\n`;
}
